"""Entry program for Meme Sprint 3: AI Agent Goes Rogue.

Copies the meme image shipped in this repository (entry.png, generated by
gen_image.py) to /output/entry.png. Standard library only, so it runs on a
bare Python 3.13 grader with no third-party packages.
"""
import os
import shutil

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "entry.png")
DST = "/output/entry.png"


def main():
    os.makedirs("/output", exist_ok=True)
    shutil.copyfile(SRC, DST)
    print("wrote", DST, os.path.getsize(DST), "bytes")


if __name__ == "__main__":
    main()
